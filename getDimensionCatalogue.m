function DimVec = getDimensionCatalogue(dataSize, dataSizeAllRS)
%% This function returns an array containing the usual dimensions contained in structures
% 
arguments
    dataSize int32 {mustBeInteger} = 0
    dataSizeAllRS int32 {mustBeInteger} = 0
end

DimVec.TimeAllRS = struct( ...
        'Name',       { 'TimeAllRS' }, ...
        'Length',     { dataSizeAllRS }, ...
        'Unlimited',  { false } );

DimVec.Time = struct(...
        'Name',      { 'Time' },...
        'Length',    { dataSize },...
        'Unlimited', { true } );

DimVec.Lon = struct(...
        'Name',      { 'Lon' },...
        'Length',    { 360 },...
        'Unlimited', { false } );

DimVec.Lat = struct(...
        'Name',      { 'Lat' },...
        'Length',    { 180 },...
        'Unlimited', { false } );

DimVec.Coef = struct(...
    'Name',         { 'Coef' }, ...
    'Length',       { 10 }, ...
    'Unlimited',    { false } );

end